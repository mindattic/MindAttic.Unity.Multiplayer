using System.Globalization;
using System.Text;
using Unity.Multiplayer.Hosting.Cli.CloudInit;
using Unity.Multiplayer.Hosting.Cli.Packaging;

namespace Unity.Multiplayer.Hosting.Cli.Local;

/// <summary>
/// Renders the <c>docker-compose.yml</c> <c>mp-host local up</c> runs on the operator's own machine
/// (UM-T31): the game service builds straight from the already-built server package's own
/// Dockerfile (<c>build: &lt;packageDirectory&gt;</c>) instead of pulling a pushed
/// <c>ghcr.io/...</c> image, since there is nothing to push to for a box that never leaves the LAN.
/// Ports follow <see cref="CloudInitRenderer.RenderCompose"/>'s binding rule (every declared port
/// open on every interface -- which is what makes LAN join by IP work -- except the health port,
/// bound to localhost only), and the saves/logs volumes mount where
/// <see cref="CloudInitRenderer.ContainerPath"/> says, under the package Dockerfile's
/// <c>WORKDIR</c> (UM-T51). The rendezvous service is included only when the operator asked for
/// one (a local dedicated server reachable beyond the LAN still needs join codes); a plain listen
/// server run for LAN-only play has no use for it.
/// </summary>
public static class LocalComposeRenderer
{
    /// <summary>The rendered compose file's name.</summary>
    public const string ComposeFileName = "docker-compose.local.yml";

    /// <summary>The rendezvous service's published TCP port, when included.</summary>
    public const int RendezvousPort = CloudInitRenderer.RendezvousPort;

    /// <summary>
    /// Renders the compose file. <paramref name="rendezvousImage"/> null omits the rendezvous
    /// service entirely (LAN-only play, join by IP); non-null adds it, same shape as
    /// <see cref="CloudInitRenderer.RenderCompose"/>.
    /// </summary>
    public static string Render(ServerPackageManifest manifest, string packageDirectory, IReadOnlyDictionary<string, string> environment, string? rendezvousImage)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        ArgumentException.ThrowIfNullOrWhiteSpace(packageDirectory);
        string absoluteDirectory = Path.GetFullPath(packageDirectory).Replace('\\', '/');

        var text = new StringBuilder();
        text.Append("# Generated by mp-host local (UM-T31). Re-running `mp-host local up` rewrites it.\n");
        text.Append("services:\n");
        text.Append("  game:\n");
        text.Append("    build: ").Append(CloudInitRenderer.YamlQuote(absoluteDirectory)).Append('\n');
        text.Append("    restart: unless-stopped\n");
        text.Append("    stop_grace_period: ").Append(((int)Math.Ceiling(manifest.StopGraceSeconds) + 5).ToString(CultureInfo.InvariantCulture)).Append("s\n");
        text.Append("    ports:\n");
        foreach (var port in manifest.Ports)
        {
            string binding = port.IsHealthPort ? "127.0.0.1:" : string.Empty;
            text.Append("      - \"").Append(binding).Append(port.Port).Append(':').Append(port.Port).Append('/').Append(port.Protocol).Append("\"\n");
        }

        text.Append("    environment:\n");
        foreach (var (key, value) in environment.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            text.Append("      ").Append(key).Append(": ").Append(CloudInitRenderer.YamlQuote(value)).Append('\n');
        }

        text.Append("    volumes:\n");
        text.Append("      - ").Append(SanitizeVolumeName(manifest)).Append("-saves:").Append(CloudInitRenderer.ContainerPath(manifest.Saves)).Append('\n');
        text.Append("      - ").Append(SanitizeVolumeName(manifest)).Append("-logs:").Append(CloudInitRenderer.ContainerPath(manifest.Logs)).Append('\n');
        if (rendezvousImage is not null)
        {
            text.Append("    depends_on:\n");
            text.Append("      - rendezvous\n");
            text.Append("  rendezvous:\n");
            text.Append("    image: ").Append(rendezvousImage).Append('\n');
            text.Append("    restart: unless-stopped\n");
            text.Append("    ports:\n");
            text.Append("      - \"").Append(RendezvousPort).Append(':').Append(RendezvousPort).Append("/tcp\"\n");
            text.Append("    environment:\n");
            text.Append("      Rendezvous__RegistrationSecret: ").Append(CloudInitRenderer.YamlQuote(environment.GetValueOrDefault("MINDATTIC_RENDEZVOUS_SECRET", ""))).Append('\n');
        }

        text.Append("volumes:\n");
        text.Append("  ").Append(SanitizeVolumeName(manifest)).Append("-saves:\n");
        text.Append("  ").Append(SanitizeVolumeName(manifest)).Append("-logs:\n");
        return text.ToString();
    }

    private static string SanitizeVolumeName(ServerPackageManifest manifest) =>
        new string((manifest.Executable.Length > 0 ? manifest.Executable : "mp-host-local").Select(c => char.IsLetterOrDigit(c) ? char.ToLowerInvariant(c) : '-').ToArray());

}
