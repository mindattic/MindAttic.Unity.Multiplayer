using System.Globalization;
using System.Text;
using Unity.Multiplayer.Hosting.Cli.Packaging;

namespace Unity.Multiplayer.Hosting.Cli.CloudInit;

/// <summary>
/// Renders the "cloud-init/startup script that runs the container + rendezvous" step for any
/// provider that lands on a plain Linux box with SSH (today: <c>GenericVpsProvisioner</c>; the
/// plain-VPS and big-cloud providers in UM-T26/UM-T27 reuse it, wrapping the same bootstrap script
/// into their own cloud-init <c>write_files</c>/<c>runcmd</c> user-data instead of running it over
/// SSH directly).
/// </summary>
public static class CloudInitRenderer
{
    /// <summary>The rendered compose file's name on the host.</summary>
    public const string ComposeFileName = "docker-compose.yml";

    /// <summary>
    /// A <c>docker-compose.yml</c> that runs the pushed image (by reference, never built on the
    /// host) beside the rendezvous service, shaped like
    /// <see cref="Unity.Multiplayer.Core.GenericVpsProfile.ComposeCompose"/> but pulling
    /// <paramref name="imageReference"/> from GHCR instead of building from the package's own
    /// Dockerfile, since mp-host already built and pushed that image in step 2.
    /// </summary>
    public static string RenderCompose(ServerPackageManifest manifest, string imageReference, string rendezvousImage, IReadOnlyDictionary<string, string> environment)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        var text = new StringBuilder();
        text.Append("# Generated by mp-host (UM-T25). Re-running `mp-host deploy`/`mp-host update` rewrites it.\n");
        text.Append("services:\n");
        text.Append("  game:\n");
        text.Append("    image: ").Append(imageReference).Append('\n');
        text.Append("    restart: unless-stopped\n");
        text.Append("    stop_grace_period: ").Append(((int)Math.Ceiling(manifest.StopGraceSeconds) + 5).ToString(CultureInfo.InvariantCulture)).Append("s\n");
        text.Append("    ports:\n");
        foreach (var port in manifest.Ports)
        {
            string binding = port.IsHealthPort ? "127.0.0.1:" : string.Empty;
            text.Append("      - \"").Append(binding).Append(port.Port).Append(':').Append(port.Port).Append('/').Append(port.Protocol).Append("\"\n");
        }

        text.Append("    environment:\n");
        foreach (var (key, value) in environment.OrderBy(kv => kv.Key, StringComparer.Ordinal))
        {
            text.Append("      ").Append(key).Append(": ").Append(YamlQuote(value)).Append('\n');
        }

        text.Append("    volumes:\n");
        text.Append("      - saves:/app/").Append(manifest.Saves).Append('\n');
        text.Append("      - logs:/app/").Append(manifest.Logs).Append('\n');
        text.Append("    depends_on:\n");
        text.Append("      - rendezvous\n");
        text.Append("  rendezvous:\n");
        text.Append("    image: ").Append(rendezvousImage).Append('\n');
        text.Append("    restart: unless-stopped\n");
        text.Append("    ports:\n");
        text.Append("      - \"8080:8080/tcp\"\n");
        text.Append("    environment:\n");
        text.Append("      Rendezvous__RegistrationSecret: ").Append(YamlQuote(environment.GetValueOrDefault("MINDATTIC_RENDEZVOUS_SECRET", ""))).Append('\n');
        text.Append("volumes:\n");
        text.Append("  saves:\n");
        text.Append("  logs:\n");
        return text.ToString();
    }

    /// <summary>
    /// The bootstrap script mp-host uploads and runs over SSH: installs Docker when missing, logs
    /// into GHCR, then pulls and (re)starts the compose stack already uploaded beside it. Exits
    /// non-zero (and therefore fails the SSH command) on any step's failure, so the pipeline sees
    /// a provisioning failure instead of silently leaving a half-started host.
    /// </summary>
    public static string RenderBootstrapScript(string ghcrRegistry, string ghcrUsername)
    {
        var text = new StringBuilder();
        text.Append("#!/bin/sh\n");
        text.Append("set -e\n");
        text.Append("if ! command -v docker >/dev/null 2>&1; then\n");
        text.Append("  curl -fsSL https://get.docker.com | sh\n");
        text.Append("fi\n");
        text.Append("if ! docker compose version >/dev/null 2>&1; then\n");
        text.Append("  echo 'docker compose plugin not found after install' >&2\n");
        text.Append("  exit 1\n");
        text.Append("fi\n");
        text.Append("cat /tmp/mp-host-ghcr-token | docker login ").Append(ghcrRegistry)
            .Append(" --username ").Append(ghcrUsername).Append(" --password-stdin\n");
        text.Append("rm -f /tmp/mp-host-ghcr-token\n");
        text.Append("docker compose -f ").Append(ComposeFileName).Append(" pull\n");
        text.Append("docker compose -f ").Append(ComposeFileName).Append(" up -d\n");
        return text.ToString();
    }

    private static string YamlQuote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
