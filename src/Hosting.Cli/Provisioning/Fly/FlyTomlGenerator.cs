using System.Text;
using Unity.Multiplayer.Hosting.Cli.CloudInit;
using Unity.Multiplayer.Hosting.Cli.Packaging;

namespace Unity.Multiplayer.Hosting.Cli.Provisioning.Fly;

/// <summary>
/// Renders a <c>fly.toml</c> for the UM-T28 Fly.io profile: documents, in Fly's own config shape,
/// exactly what <see cref="FlyProvisioner"/> asks the Machines API for directly (mp-host's actual
/// deploy never shells out to <c>flyctl deploy</c> against this file -- see <see cref="FlyProvisioner"/>'s
/// class doc). It exists so an operator can hand the same app to <c>flyctl deploy</c>/<c>flyctl
/// machine clone</c>/Fly's dashboard later without guessing at the shape mp-host used.
/// </summary>
public static class FlyTomlGenerator
{
    /// <summary>Rendezvous runs as a second machine in the same Fly app, under its own process group.</summary>
    public const string ProcessGroupRendezvousMode = "process-group";

    /// <summary>Rendezvous runs as its own, separate Fly app (<c>&lt;app&gt;-rendezvous</c>).</summary>
    public const string AppRendezvousMode = "app";

    /// <summary>
    /// The hostname a Fly machine's game process must bind for its UDP service -- Fly's edge
    /// proxies UDP packets to this address rather than <c>0.0.0.0</c>; binding anywhere else means
    /// the UDP service never receives a packet. <see cref="FlyProvisioner"/> injects this as
    /// <c>MINDATTIC_BIND_HOST</c> in every machine's environment.
    /// </summary>
    public const string UdpBindHost = "fly-global-services";

    /// <summary>
    /// A <c>fly.toml</c> for <paramref name="appName"/>: a UDP <c>[[services]]</c> entry for the
    /// manifest's game port, a <c>[[vm]]</c> block for <paramref name="size"/>, and -- only when
    /// <paramref name="rendezvousMode"/> is <see cref="ProcessGroupRendezvousMode"/> -- a second
    /// <c>[processes]</c> group plus its own TCP <c>[[services]]</c> entry for rendezvous. In
    /// <see cref="AppRendezvousMode"/> this file describes the game app alone; rendezvous gets its
    /// own separate <c>fly.toml</c> (render this same method again with <paramref name="appName"/>
    /// suffixed <c>-rendezvous</c>, a TCP-only manifest, and no rendezvous mode section of its own).
    /// </summary>
    public static string Render(
        string appName,
        string region,
        string size,
        string imageReference,
        ServerPackageManifest manifest,
        string rendezvousMode,
        string? rendezvousImage = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(appName);
        ArgumentException.ThrowIfNullOrWhiteSpace(region);
        ArgumentException.ThrowIfNullOrWhiteSpace(size);
        ArgumentNullException.ThrowIfNull(manifest);
        var gamePort = manifest.GamePort ?? throw new ArgumentException("The manifest has no declared game port.", nameof(manifest));

        var text = new StringBuilder();
        text.Append("# Generated by mp-host (UM-T28). Re-running `mp-host deploy`/`mp-host update` rewrites it.\n");
        text.Append("# mp-host's actual deploy talks to Fly's Machines API directly, not `flyctl deploy` against\n");
        text.Append("# this file -- it is handed to you for `flyctl deploy`/`flyctl machine clone`/the dashboard.\n");
        text.Append("# The game process must bind \"").Append(UdpBindHost).Append("\" for its UDP port (Fly's edge\n");
        text.Append("# proxies UDP there, never to 0.0.0.0); mp-host sets MINDATTIC_BIND_HOST to it automatically.\n");
        text.Append("# A dedicated IPv4 is required for UDP (`flyctl ips allocate-v4 --app ").Append(appName).Append("`);\n");
        text.Append("# mp-host allocates one itself as part of `mp-host deploy`.\n");
        text.Append("app = \"").Append(appName).Append("\"\n");
        text.Append("primary_region = \"").Append(region).Append("\"\n");
        text.Append('\n');
        text.Append("[build]\n");
        text.Append("  image = \"").Append(imageReference).Append("\"\n");
        text.Append('\n');
        text.Append("[env]\n");
        text.Append("  MINDATTIC_BIND_HOST = \"").Append(UdpBindHost).Append("\"\n");

        bool colocatedRendezvous = string.Equals(rendezvousMode, ProcessGroupRendezvousMode, StringComparison.OrdinalIgnoreCase);
        text.Append('\n');
        if (colocatedRendezvous)
        {
            text.Append("[processes]\n");
            text.Append("  app = \"\"\n");
            text.Append("  rendezvous = \"\"\n");
            text.Append('\n');
        }

        text.Append("[[vm]]\n");
        text.Append("  size = \"").Append(size).Append("\"\n");
        text.Append("  processes = [\"app\"]\n");
        text.Append('\n');
        text.Append("[[services]]\n");
        text.Append("  protocol = \"").Append(gamePort.Protocol).Append("\"\n");
        text.Append("  internal_port = ").Append(gamePort.Port).Append('\n');
        text.Append("  processes = [\"app\"]\n");
        text.Append('\n');
        text.Append("  [[services.ports]]\n");
        text.Append("    port = ").Append(gamePort.Port).Append('\n');

        if (manifest.HealthPort is { } health)
        {
            text.Append('\n');
            text.Append("  # Health port stays private -- no [[services.ports]] for it; Fly's own machine checks\n");
            text.Append("  # (or mp-host's post-provision poll) reach it over the machine's private network.\n");
            text.Append("  [[services.tcp_checks]]\n");
            text.Append("    port = ").Append(health.Port).Append('\n');
        }

        if (colocatedRendezvous)
        {
            text.Append('\n');
            text.Append("[[vm]]\n");
            text.Append("  size = \"").Append(size).Append("\"\n");
            text.Append("  processes = [\"rendezvous\"]\n");
            text.Append('\n');
            text.Append("[[services]]\n");
            text.Append("  protocol = \"tcp\"\n");
            text.Append("  internal_port = ").Append(CloudInitRenderer.RendezvousPort).Append('\n');
            text.Append("  processes = [\"rendezvous\"]\n");
            text.Append('\n');
            text.Append("  [[services.ports]]\n");
            text.Append("    port = ").Append(CloudInitRenderer.RendezvousPort).Append('\n');
            text.Append('\n');
            text.Append("# The rendezvous process group runs a different image (").Append(rendezvousImage ?? "ghcr.io/mindattic/rendezvous:latest")
                .Append(") than [build].image above.\n");
            text.Append("# fly.toml alone can't express a second image for one process group -- mp-host creates the\n");
            text.Append("# rendezvous machine straight through the Machines API with its own image; this file\n");
            text.Append("# documents its port/service shape, not the exact image it runs.\n");
        }

        return text.ToString();
    }
}
