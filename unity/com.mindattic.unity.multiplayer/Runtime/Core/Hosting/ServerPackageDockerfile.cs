using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace MindAttic.Unity.Multiplayer.Core
{
    /// <summary>
    /// The Dockerfile and .dockerignore for a server package, for profiles that run it as a container. The image runs
    /// <c>start.sh</c> as a non-root user, exposes the declared ports, keeps <c>Saves/</c> and <c>Logs/</c> in volumes,
    /// stops with SIGTERM and probes the health endpoint.
    /// </summary>
    public static class ServerPackageDockerfile
    {
        /// <summary>The base image used unless the profile names another.</summary>
        public const string DefaultBaseImage = "ubuntu:24.04";

        /// <summary>The non-root user the server runs as.</summary>
        public const string User = "server";

        /// <summary>The package folder inside the image.</summary>
        public const string WorkDir = "/srv/game";

        /// <summary>The Dockerfile's name.</summary>
        public const string FileName = "Dockerfile";

        /// <summary>The .dockerignore's name.</summary>
        public const string IgnoreFileName = ".dockerignore";

        /// <summary>The Dockerfile text for <paramref name="spec"/>.</summary>
        /// <exception cref="ArgumentNullException"><paramref name="spec"/> is null.</exception>
        public static string Compose(ServerPackageSpec spec, string baseImage = null)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            string image = string.IsNullOrWhiteSpace(baseImage) ? DefaultBaseImage : baseImage.Trim();
            string logsPath = ContainerPath(spec.Settings.LogsDirectory);
            string savesPath = ContainerPath(spec.Settings.SavesDirectory);
            string logs = ServerPackageSpec.ShellQuote(logsPath);
            string saves = ServerPackageSpec.ShellQuote(savesPath);
            IReadOnlyList<DeclaredPort> ports = spec.Ports;
            bool health = spec.Settings.HealthPort != 0;

            var text = new StringBuilder();
            text.Append("# Generated by MindAttic.Unity.Multiplayer (Build Server Package > ").Append(spec.Profile.Id).Append("). Rebuilding rewrites it.\n");
            text.Append("#\n");
            text.Append("#   docker build -t game-server .\n");
            text.Append("#   docker run --rm");
            foreach (DeclaredPort port in ports)
            {
                text.Append(" -p ").Append(port.Port).Append(':').Append(port.Port).Append('/').Append(port.ProtocolName);
            }

            text.Append(" game-server\n");
            text.Append("#\n");
            text.Append("# Arguments after the image name go to start.sh and override server.json (-maxPlayers 4 -name \"Friday game\").\n");
            text.Append("# Secrets go in the environment, never the image: -e MINDATTIC_RENDEZVOUS_SECRET=... -e MINDATTIC_SERVER_PASSWORD=...\n");
            text.Append("FROM ").Append(image).Append('\n');
            text.Append('\n');
            text.Append("RUN apt-get update \\\n");
            text.Append(" && apt-get install -y --no-install-recommends ca-certificates").Append(health ? " curl" : string.Empty).Append(" \\\n");
            text.Append(" && rm -rf /var/lib/apt/lists/* \\\n");
            text.Append(" && useradd --create-home --shell /usr/sbin/nologin ").Append(User).Append('\n');
            text.Append('\n');
            text.Append("WORKDIR ").Append(WorkDir).Append('\n');
            text.Append("COPY --chown=").Append(User).Append(':').Append(User).Append(" . .\n");
            text.Append("RUN chmod +x ").Append(ServerPackageSpec.StartScriptName).Append(' ').Append(spec.ExecutableName)
                .Append(" && mkdir -p ").Append(logs).Append(' ').Append(saves)
                .Append(" && chown ").Append(User).Append(':').Append(User).Append(' ').Append(logs).Append(' ').Append(saves).Append('\n');
            text.Append('\n');
            text.Append("USER ").Append(User).Append('\n');
            foreach (DeclaredPort port in ports)
            {
                text.Append("EXPOSE ").Append(port.Port).Append('/').Append(port.ProtocolName).Append('\n');
            }

            text.Append("VOLUME [").Append(ServerPackageSpec.Quote(savesPath)).Append(", ").Append(ServerPackageSpec.Quote(logsPath)).Append("]\n");
            text.Append("STOPSIGNAL SIGTERM\n");
            if (health)
            {
                text.Append("HEALTHCHECK --interval=15s --timeout=3s --start-period=60s --retries=3 \\\n");
                text.Append("    CMD curl -fsS http://127.0.0.1:").Append(spec.Settings.HealthPort.ToString(CultureInfo.InvariantCulture))
                    .Append(ServerSettings.HealthPath).Append(" || exit 1\n");
            }

            text.Append("ENTRYPOINT [\"./").Append(ServerPackageSpec.StartScriptName).Append("\"]\n");
            return text.ToString();
        }

        /// <summary>
        /// The .dockerignore: Unity's debug-symbol and backup folders, which must not ship, local logs and saves, which
        /// must not be baked into the image, and the Docker files themselves.
        /// </summary>
        /// <exception cref="ArgumentNullException"><paramref name="spec"/> is null.</exception>
        public static string ComposeIgnore(ServerPackageSpec spec, IEnumerable<string> alsoIgnore = null)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            var text = new StringBuilder();
            text.Append("# Generated by MindAttic.Unity.Multiplayer: keep debug symbols, local logs and saves out of the image.\n");
            text.Append("*_BurstDebugInformation_DoNotShip\n");
            text.Append("*_BackUpThisFolder_ButDontShipItWithYourGame\n");
            if (ServerPackageSpec.IsInsidePackage(spec.Settings.LogsDirectory))
            {
                text.Append(spec.Settings.LogsDirectory.Trim().TrimEnd('/')).Append('\n');
            }

            if (ServerPackageSpec.IsInsidePackage(spec.Settings.SavesDirectory))
            {
                text.Append(spec.Settings.SavesDirectory.Trim().TrimEnd('/')).Append('\n');
            }

            text.Append(FileName).Append('\n');
            text.Append(IgnoreFileName).Append('\n');
            if (alsoIgnore != null)
            {
                foreach (string pattern in alsoIgnore)
                {
                    if (!string.IsNullOrWhiteSpace(pattern))
                    {
                        text.Append(pattern.Trim()).Append('\n');
                    }
                }
            }

            return text.ToString();
        }

        /// <summary>A package folder's path inside the container: absolute paths as given, relative ones under <see cref="WorkDir"/>.</summary>
        public static string ContainerPath(string directory)
        {
            string dir = string.IsNullOrWhiteSpace(directory) ? "." : directory.Trim().Replace('\\', '/').TrimEnd('/');
            return dir.StartsWith("/", StringComparison.Ordinal) ? dir : WorkDir + "/" + dir;
        }
    }
}
