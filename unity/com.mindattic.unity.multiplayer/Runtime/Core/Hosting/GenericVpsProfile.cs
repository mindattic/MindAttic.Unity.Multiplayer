using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace Unity.Multiplayer.Core
{
    /// <summary>
    /// The default hosting profile: the package as a Docker image, run beside the rendezvous service with Docker Compose
    /// on any UDP-capable CPU VPS (Hetzner, Vultr, DigitalOcean and similar). Players connect over UDP and join by code.
    /// </summary>
    /// <remarks>
    /// Adds a Dockerfile, a .dockerignore, <c>docker-compose.yml</c> (the game server plus the rendezvous service, saves
    /// and logs in named volumes, the health port bound to localhost) and <c>HOSTING.txt</c> (the steps, and the
    /// firewall ports to open).
    /// </remarks>
    public sealed class GenericVpsProfile : IHostingProfile
    {
        /// <summary>This profile's <see cref="Id"/>.</summary>
        public const string ProfileId = "GenericVps";

        /// <summary>The compose file's name.</summary>
        public const string ComposeFileName = "docker-compose.yml";

        /// <summary>The notes file's name.</summary>
        public const string NotesFileName = "HOSTING.txt";

        /// <summary>The rendezvous service's port in the compose file (its image's default).</summary>
        public const ushort RendezvousPort = 8080;

        /// <inheritdoc />
        public string Id
        {
            get { return ProfileId; }
        }

        /// <inheritdoc />
        public string DisplayName
        {
            get { return "Generic VPS (Docker + rendezvous)"; }
        }

        /// <inheritdoc />
        public string Description
        {
            get { return "A Docker image plus the rendezvous service on any UDP-capable VPS; players connect over UDP and join by code."; }
        }

        /// <summary>The Docker base image; null for <see cref="ServerPackageDockerfile.DefaultBaseImage"/>.</summary>
        public string BaseImage { get; set; }

        /// <inheritdoc />
        public void Configure(ServerPackageSpec spec)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            // Dedicated servers here publish join codes through the rendezvous service in the same compose file.
            if (spec.Config.JoinCodes == JoinCodeProvider.Relay)
            {
                spec.Config.JoinCodes = JoinCodeProvider.Auto;
            }
        }

        /// <inheritdoc />
        public IReadOnlyList<ServerPackageFile> CreateFiles(ServerPackageSpec spec)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            return new[]
            {
                ServerPackageFile.Text(ServerPackageDockerfile.FileName, ServerPackageDockerfile.Compose(spec, BaseImage)),
                ServerPackageFile.Text(ServerPackageDockerfile.IgnoreFileName, ServerPackageDockerfile.ComposeIgnore(spec, new[] { ComposeFileName, NotesFileName })),
                ServerPackageFile.Text(ComposeFileName, ComposeCompose(spec)),
                ServerPackageFile.Text(NotesFileName, ComposeNotes(spec)),
            };
        }

        /// <summary>The <c>docker-compose.yml</c> text.</summary>
        public static string ComposeCompose(ServerPackageSpec spec)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            string grace = ((int)Math.Ceiling(spec.Settings.ShutdownGraceSeconds) + 5).ToString(CultureInfo.InvariantCulture);
            var text = new StringBuilder();
            text.Append("# Generated by Unity.Multiplayer (Build Server Package > GenericVps). Rebuilding rewrites it.\n");
            text.Append("#\n");
            text.Append("# The game server and the rendezvous service on one VPS. Build the rendezvous image once from a\n");
            text.Append("# Unity.Multiplayer checkout (docker build -f server/Rendezvous/Dockerfile -t mindattic-rendezvous .),\n");
            text.Append("# copy this folder to the VPS, then:\n");
            text.Append("#\n");
            text.Append("#   export PUBLIC_ADDRESS=<the VPS's public IP> RENDEZVOUS_SECRET=<a long random string>\n");
            text.Append("#   docker compose up -d --build\n");
            text.Append("#\n");
            text.Append("# Players use http://<PUBLIC_ADDRESS>:").Append(RendezvousPort).Append(" as the rendezvous URL (put TLS in front of it for the internet).\n");
            text.Append("services:\n");
            text.Append("  game:\n");
            text.Append("    build: .\n");
            text.Append("    restart: unless-stopped\n");
            text.Append("    stop_grace_period: ").Append(grace).Append("s\n");
            text.Append("    ports:\n");
            foreach (DeclaredPort port in spec.Ports)
            {
                string binding = port.Name == DeclaredPort.HealthName ? "127.0.0.1:" : string.Empty;
                text.Append("      - \"").Append(binding).Append(port.Port).Append(':').Append(port.Port).Append('/').Append(port.ProtocolName).Append("\"\n");
            }

            text.Append("    environment:\n");
            text.Append("      MINDATTIC_RENDEZVOUS_URL: http://rendezvous:").Append(RendezvousPort).Append('\n');
            text.Append("      MINDATTIC_RENDEZVOUS_SECRET: ${RENDEZVOUS_SECRET:?set RENDEZVOUS_SECRET}\n");
            text.Append("      MINDATTIC_PUBLIC_ADDRESS: ${PUBLIC_ADDRESS:?set PUBLIC_ADDRESS to this VPS's public IP}\n");
            text.Append("      MINDATTIC_SERVER_PASSWORD: ${SERVER_PASSWORD:-}\n");
            text.Append("    volumes:\n");
            text.Append("      - saves:").Append(ServerPackageDockerfile.ContainerPath(spec.Settings.SavesDirectory)).Append('\n');
            text.Append("      - logs:").Append(ServerPackageDockerfile.ContainerPath(spec.Settings.LogsDirectory)).Append('\n');
            text.Append("    depends_on:\n");
            text.Append("      - rendezvous\n");
            text.Append("  rendezvous:\n");
            text.Append("    image: ${RENDEZVOUS_IMAGE:-mindattic-rendezvous}\n");
            text.Append("    restart: unless-stopped\n");
            text.Append("    ports:\n");
            text.Append("      - \"").Append(RendezvousPort).Append(':').Append(RendezvousPort).Append("/tcp\"\n");
            text.Append("    environment:\n");
            text.Append("      Rendezvous__RegistrationSecret: ${RENDEZVOUS_SECRET:?set RENDEZVOUS_SECRET}\n");
            text.Append("volumes:\n");
            text.Append("  saves:\n");
            text.Append("  logs:\n");
            return text.ToString();
        }

        /// <summary>The <c>HOSTING.txt</c> text.</summary>
        public static string ComposeNotes(ServerPackageSpec spec)
        {
            if (spec == null)
            {
                throw new ArgumentNullException(nameof(spec));
            }

            var text = new StringBuilder();
            text.Append("Hosting profile: GenericVps (the default)\n");
            text.Append("=========================================\n\n");
            text.Append("Runs this server package as a Docker container beside the rendezvous service on one UDP-capable CPU VPS\n");
            text.Append("(Hetzner, Vultr, DigitalOcean and similar). Nothing here is tied to one provider.\n\n");
            text.Append("1. Rent a small Linux VPS with Docker installed and a public IPv4 address.\n");
            text.Append("2. Open these ports in the provider's firewall:\n");
            foreach (DeclaredPort port in spec.Ports)
            {
                if (port.Name == DeclaredPort.HealthName)
                {
                    continue;
                }

                text.Append("     ").Append(port.Port).Append('/').Append(port.ProtocolName).Append("   ").Append(port.Purpose).Append('\n');
            }

            text.Append("     ").Append(RendezvousPort).Append("/tcp   The rendezvous service: players resolve join codes here.\n");
            if (spec.Settings.HealthPort != 0)
            {
                text.Append("   The health endpoint (").Append(spec.Settings.HealthPort).Append("/tcp, GET ").Append(ServerSettings.HealthPath)
                    .Append(") is bound to localhost; open it only for an outside monitor.\n");
            }

            text.Append("3. Copy this folder to the VPS, set PUBLIC_ADDRESS and RENDEZVOUS_SECRET, and run docker compose up -d --build\n");
            text.Append("   (see docker-compose.yml). Set SERVER_PASSWORD for a private server.\n");
            text.Append("4. Edit server.json to change the name, player cap or port; restart with docker compose restart game.\n");
            text.Append("   Saves and logs live in the compose volumes \"saves\" and \"logs\" and survive rebuilds.\n");
            text.Append("5. docker compose stop sends SIGTERM: the server tells players, saves and exits cleanly.\n");
            return text.ToString();
        }
    }
}
