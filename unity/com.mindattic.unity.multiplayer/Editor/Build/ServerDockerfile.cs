using System;
using System.Collections.Generic;
using System.Text;
using Unity.Multiplayer.Core;

namespace Unity.Multiplayer.Editor
{
    /// <summary>
    /// Writes the Dockerfile (and .dockerignore) placed beside a Linux dedicated server build, so the build folder is a
    /// ready Docker build context: <c>docker build -t game-server .</c> then
    /// <c>docker run -p 7777:7777/udp game-server</c>.
    /// </summary>
    /// <remarks>
    /// The server runs as a non-root user with <c>-batchmode -nographics -logFile -</c> (the log goes to stdout, where
    /// <c>docker logs</c> reads it) and <c>-mode server -port -transport</c>. The entrypoint is exec form, so
    /// arguments after the image name (<c>-maxplayers 4</c>, <c>-rendezvous https://...</c>) are appended and override
    /// the defaults. The rendezvous secret goes in the environment (<c>-e MINDATTIC_RENDEZVOUS_SECRET=...</c>), never the image.
    /// </remarks>
    public static class ServerDockerfile
    {
        /// <summary>The base image used unless the build options name another.</summary>
        public const string DefaultBaseImage = "ubuntu:24.04";

        /// <summary>The non-root user the server runs as inside the container.</summary>
        public const string User = "server";

        /// <summary>The folder the build is copied to inside the image.</summary>
        public const string WorkDir = "/srv/game";

        /// <summary>The server's launch arguments, executable first.</summary>
        public static List<string> EntryPoint(string executableName, ushort port, TransportKind transport, IEnumerable<string> extraArgs = null)
        {
            var args = new List<string>
            {
                "./" + executableName,
                "-batchmode",
                "-nographics",
                "-logFile",
                "-",
                NetCommandLine.ModeArg,
                "server",
                NetCommandLine.PortArg,
                port.ToString(System.Globalization.CultureInfo.InvariantCulture),
                NetCommandLine.TransportArg,
                transport == TransportKind.WebSocket ? "websocket" : "udp",
            };

            if (extraArgs != null)
            {
                foreach (string arg in extraArgs)
                {
                    if (!string.IsNullOrEmpty(arg))
                    {
                        args.Add(arg);
                    }
                }
            }

            return args;
        }

        /// <summary>The Dockerfile text.</summary>
        /// <exception cref="ArgumentException"><paramref name="executableName"/> is empty or has characters a file name in the image cannot.</exception>
        public static string Compose(string executableName, ushort port, TransportKind transport, string baseImage = null, IEnumerable<string> extraArgs = null)
        {
            if (string.IsNullOrEmpty(executableName) || DedicatedServerBuild.SanitizeExecutableName(executableName) != executableName)
            {
                throw new ArgumentException("'" + executableName + "' is not a valid server executable name (letters, digits, '.', '_' and '-' only).", nameof(executableName));
            }

            if (port == 0)
            {
                throw new ArgumentOutOfRangeException(nameof(port), "The server needs a fixed port.");
            }

            string image = string.IsNullOrWhiteSpace(baseImage) ? DefaultBaseImage : baseImage.Trim();
            string protocol = transport == TransportKind.WebSocket ? "tcp" : "udp";
            string p = port.ToString(System.Globalization.CultureInfo.InvariantCulture);
            var text = new StringBuilder();
            text.Append("# Generated by Unity.Multiplayer (MindAttic > Multiplayer > Build Dedicated Server (Linux)).\n");
            text.Append("# Rebuilding the server rewrites this file.\n");
            text.Append("#\n");
            text.Append("#   docker build -t game-server .\n");
            text.Append("#   docker run --rm -p ").Append(p).Append(':').Append(p).Append('/').Append(protocol).Append(" game-server\n");
            text.Append("#\n");
            text.Append("# Arguments after the image name are appended to the server's command line (-maxplayers 4,\n");
            text.Append("# -rendezvous https://codes.example.com, -publicaddress 203.0.113.7). Pass secrets as environment\n");
            text.Append("# variables, never in the image: -e MINDATTIC_RENDEZVOUS_SECRET=... (also MINDATTIC_RENDEZVOUS_URL,\n");
            text.Append("# MINDATTIC_PUBLIC_ADDRESS).\n");
            text.Append("FROM ").Append(image).Append('\n');
            text.Append('\n');
            text.Append("RUN apt-get update \\\n");
            text.Append(" && apt-get install -y --no-install-recommends ca-certificates \\\n");
            text.Append(" && rm -rf /var/lib/apt/lists/* \\\n");
            text.Append(" && useradd --create-home --shell /usr/sbin/nologin ").Append(User).Append('\n');
            text.Append('\n');
            text.Append("WORKDIR ").Append(WorkDir).Append('\n');
            text.Append("COPY --chown=").Append(User).Append(':').Append(User).Append(" . .\n");
            text.Append("RUN chmod +x ").Append(executableName).Append('\n');
            text.Append('\n');
            text.Append("USER ").Append(User).Append('\n');
            text.Append("EXPOSE ").Append(p).Append('/').Append(protocol).Append('\n');
            text.Append("STOPSIGNAL SIGTERM\n");
            text.Append("ENTRYPOINT [");
            List<string> args = EntryPoint(executableName, port, transport, extraArgs);
            for (int i = 0; i < args.Count; i++)
            {
                if (i > 0)
                {
                    text.Append(", ");
                }

                text.Append(JsonString(args[i]));
            }

            text.Append("]\n");
            return text.ToString();
        }

        /// <summary>
        /// The .dockerignore beside the Dockerfile: Unity's debug-symbol and backup folders, which must not ship, and the
        /// Docker files themselves.
        /// </summary>
        public static string ComposeIgnore()
        {
            return "# Generated by Unity.Multiplayer: keep Unity's debug symbols and IL2CPP backups out of the image.\n"
                + "*_BurstDebugInformation_DoNotShip\n"
                + "*_BackUpThisFolder_ButDontShipItWithYourGame\n"
                + "Dockerfile\n"
                + ".dockerignore\n";
        }

        private static string JsonString(string value)
        {
            var text = new StringBuilder("\"");
            foreach (char c in value)
            {
                switch (c)
                {
                    case '"':
                        text.Append("\\\"");
                        break;
                    case '\\':
                        text.Append("\\\\");
                        break;
                    default:
                        if (c < ' ')
                        {
                            text.Append("\\u").Append(((int)c).ToString("x4"));
                        }
                        else
                        {
                            text.Append(c);
                        }

                        break;
                }
            }

            return text.Append('"').ToString();
        }
    }
}
